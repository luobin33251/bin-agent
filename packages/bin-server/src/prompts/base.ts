const WEEKDAYS = ['日', '一', '二', '三', '四', '五', '六'];

/**
 * 组装系统提示词。
 *
 * 必须每次请求现算，把「今天几号」告诉模型：
 * 用户说的「8月3日」「下周三」「月底」都要换算成完整日期，
 * 而模型自己不知道当前日期——不给它，它就会把年份猜错（实测把 8 月 3 日记成了去年）。
 */
export function buildSystemPrompt(now = new Date()): string {
  const date = `${now.getFullYear()}-${pad(now.getMonth() + 1)}-${pad(now.getDate())}`;
  const time = `${pad(now.getHours())}:${pad(now.getMinutes())}`;

  return `${basePrompt}

## 当前时间

今天是 ${date}（星期${WEEKDAYS[now.getDay()]}），现在是 ${time}。

用户说「8月3日」「下周三」「月底」这类省略年份或相对的时间时，一律以上面的日期为基准换算成完整日期，
不要凭感觉猜年份。换算结果填进 occurred_at。
`;
}

function pad(value: number): string {
  return String(value).padStart(2, '0');
}